UNKNOWN_NOTE = "НАЗВАНИЕ НЕ УСТАНОВЛЕНО; ЦЕН В ПРАЙС-ЛИСТАХ НЕТ; ПРОВЕРИТЬ ВИЗУАЛЬНО"
