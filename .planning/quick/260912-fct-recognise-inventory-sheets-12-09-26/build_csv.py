UNKNOWN_HINT = {
    "19140": "САМ КОД ПОМЕЧЕН НА ЛИСТЕ «???»; ПОДПИСЬ НА ЛИСТЕ: SWEDISH NOURISHING SPA FOOT MASK",
}

NO_EXPIRY_MARKERS = {"бу", "без", "нет"}
# «бу» is a CONDITION marker, not an expiry: the operator confirmed on 2026-09-12
# that it means «бывшее в употреблении». It goes into the comment column after
# the shelf, which makes the importer open a fresh batch and forbid a top-up.
CONDITION_MARKERS = {"бу": "б/у"}


def expiry_iso(written: str) -> str:
    if not written or written in NO_EXPIRY_MARKERS:
        return ""
    month, year = written.split("/")
    y = 2000 + int(year)
    m = int(month)
    return f"{y:04d}-{m:02d}-{calendar.monthrange(y, m)[1]:02d}"


def main() -> None:
    con = sqlite3.connect(ROOT / "data" / "myorishop.db")
    names = dict(con.execute("select code, name from dictionary").fetchall())

    out = ROOT / "reports" / "оприходование-2026-09-12.csv"
    rows = 0
    units = 0
    missing = []
    with out.open("w", encoding="utf-8-sig", newline="") as fh:
        w = csv.writer(fh, delimiter=";", lineterminator="\n")
        w.writerow(["Полка", "Код", "Наименование (из справочника)", "Кол-во",
                    "Срок годности", "Срок (как в записи)", "Комментарий",
                    "Файл-источник", "Проверить"])
        for src, shelf, code, parts in SHEETS:
            name = names.get(code)
            note = CHECK.get((src, code), "")
            if name is None:
                # Same convention as reports/оприходование-офис-2026-08-31.csv.
                missing.append((src, code))
                name = f"Не опознан (код {code})"
                note = UNKNOWN_HINT.get(code, UNKNOWN_NOTE)
            for qty, written in parts:
                condition = CONDITION_MARKERS.get(written, "")
                comment = f"полка {shelf}, {condition}" if condition else f"полка {shelf}"
                w.writerow([shelf, code, name, qty, expiry_iso(written), written,
                            comment, src, note])
                rows += 1
                units += qty

    print(f"строк: {rows}")
    print(f"штук:  {units}")
    print(f"кодов: {len({c for _, _, c, _ in SHEETS})}")
    print(f"полок: {sorted({s for _, s, _, _ in SHEETS}, key=int)}")
    if missing:
        print("НЕТ В СПРАВОЧНИКЕ:", missing)


if __name__ == "__main__":
    main()
